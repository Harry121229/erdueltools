use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum Lang {
    Zh = 0,
    En = 1,
    Ja = 2,
    Fr = 3,
}

impl Lang {
    pub fn from_code(code: &str) -> Option<Self> {
        match code.trim().to_ascii_lowercase().as_str() {
            "zh" | "zh-cn" | "cn" | "chinese" => Some(Self::Zh),
            "en" | "eng" | "english" => Some(Self::En),
            "ja" | "jp" | "japanese" => Some(Self::Ja),
            "fr" | "fra" | "french" => Some(Self::Fr),
            "ko" | "kr" | "korean" => Some(Self::En),
            _ => None,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::Zh => "zh",
            Self::En => "en",
            Self::Ja => "ja",
            Self::Fr => "fr",
        }
    }

    pub fn next(self) -> Self {
        match self {
            Self::Zh => Self::En,
            Self::En => Self::Ja,
            Self::Ja => Self::Fr,
            Self::Fr => Self::Zh,
        }
    }

    pub fn from_u8(value: u8) -> Self {
        match value {
            1 => Self::En,
            2 => Self::Ja,
            3 => Self::Fr,
            _ => Self::Zh,
        }
    }
}

static LANG: AtomicU8 = AtomicU8::new(Lang::En as u8);

pub fn language() -> Lang {
    Lang::from_u8(LANG.load(Ordering::SeqCst))
}

pub fn set_language(lang: Lang) {
    LANG.store(lang as u8, Ordering::SeqCst);
}

